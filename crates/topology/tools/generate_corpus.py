"""Generates src/corpus.rs: biconnected graphs with the planarity answer of an independent implementation.

Dev-only, not part of the build. Run with networkx installed:
    python3 crates/topology/tools/generate_corpus.py > crates/topology/src/corpus.rs
networkx is BSD-3-Clause; it is used only as an oracle here, no code is copied.
"""
import random
import networkx as nx

rng = random.Random(20261021)
graphs = []
while len(graphs) < 300:
    n = rng.randint(4, 9)
    pairs = [(a, b) for a in range(n) for b in range(a + 1, n)]
    m = rng.randint(n, min(len(pairs), 3 * n))
    edges = sorted(rng.sample(pairs, m))
    g = nx.Graph()
    g.add_nodes_from(range(n))
    g.add_edges_from(edges)
    if nx.is_biconnected(g):
        graphs.append((n, edges))
for named in [nx.complete_graph(5), nx.petersen_graph(), nx.dodecahedral_graph()]:
    edges = sorted(tuple(sorted(e)) for e in named.edges())
    graphs.append((named.number_of_nodes(), edges))
for n, edges in graphs:
    assert all(0 <= a < b < n for a, b in edges), "endpoint outside 0..n"

print("//! Generated by crates/topology/tools/generate_corpus.py; do not edit by hand.")
print("//! `(vertices, edges, planar)` for biconnected graphs; `planar` is the answer of networkx 3.7.")
print("#![allow(clippy::type_complexity)]")
print()
print("pub const CORPUS: &[(usize, &[(usize, usize)], bool)] = &[")
planar_count = 0
for n, edges in graphs:
    g = nx.Graph()
    g.add_nodes_from(range(n))
    g.add_edges_from(edges)
    planar, _ = nx.check_planarity(g)
    planar_count += planar
    body = ", ".join(f"({a}, {b})" for a, b in edges)
    print(f"    ({n}, &[{body}], {'true' if planar else 'false'}),")
print("];")
import sys
print(f"// {planar_count} planar, {len(graphs) - planar_count} nonplanar", file=sys.stderr)
