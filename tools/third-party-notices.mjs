#!/usr/bin/env node
// Collects the license notices of the Rust crates that are linked into a build of this repository, from the sources
// cargo has already fetched, and renders them as one Markdown file. `tools/npm-prepack.mjs` (`--wasm`, `--query-wasm`) puts the
// result into the npm package that ships the module, as THIRD_PARTY_NOTICES.md: the MIT and Apache-2.0 licenses of these crates require their
// copyright and license notices to accompany a distribution, and a WASM binary contains the crates themselves.
//
//   node tools/third-party-notices.mjs [--package arqlet-wasm] [--target wasm32-unknown-unknown] [--check]
//
// Prints the Markdown to standard output. With --check it prints nothing and exits with 1 when a crate has no license file.
//
// Which crates: what `cargo tree` links into the package for the target, along normal dependencies and without proc-macro
// crates (their code runs at build time and is not distributed). The crates of this workspace are left out; they carry
// the project's own license. Nothing here reads the network: cargo's own sources are used, and the lock file is honoured.
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readdirSync, readFileSync, statSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(import.meta.dirname, '..');
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)/i;

function cargo(args) {
  return execFileSync('cargo', args, {cwd: root, encoding: 'utf8', maxBuffer: 512 * 1024 * 1024, stdio: ['ignore', 'pipe', 'inherit']});
}

/** The registry (and git) crates linked into `pkg` for `target`, as `[{name, version}]`, sorted by name and version. */
export function linkedCrates(pkg, target) {
  const out = cargo(['tree', '-p', pkg, '--target', target, '-e', 'normal,no-proc-macro', '--prefix', 'none', '--locked']);
  const found = new Map();
  for (const line of out.split('\n')) {
    const m = /^(\S+) v(\S+)(?: \(([^*][^)]*)\))?(?: \(\*\))?$/.exec(line.trim());
    if (!m) continue;
    const [, name, version, where] = m;
    // A crate of this workspace prints its path: `/…` or `C:\…`.
    if (where && (where.startsWith('/') || /^[A-Za-z]:[\\/]/.test(where))) continue;
    found.set(`${name}@${version}`, {name, version});
  }
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

/** What `cargo metadata` knows about each crate: license expression, repository and the directory of its sources. */
function metadataByCrate() {
  const meta = JSON.parse(cargo(['metadata', '--format-version', '1', '--locked']));
  return new Map(meta.packages.map(p => [`${p.name}@${p.version}`, p]));
}

/** The license files of one crate: `[{file, text}]`, sorted by file name. */
function licenseFiles(dir) {
  return readdirSync(dir)
    .filter(f => LICENSE_FILE.test(f) && statSync(join(dir, f)).isFile())
    .sort()
    .map(file => ({file, text: readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trimEnd()}));
}

/** Every crate with its license data; `files` is empty for a crate that ships no license file. */
export function collect(pkg = 'arqlet-wasm', target = 'wasm32-unknown-unknown') {
  const byCrate = metadataByCrate();
  return linkedCrates(pkg, target).map(({name, version}) => {
    const p = byCrate.get(`${name}@${version}`);
    if (!p) throw new Error(`cargo metadata does not list ${name} ${version}`);
    return {name, version, license: p.license ?? '(none declared)', repository: p.repository ?? '', files: licenseFiles(dirname(p.manifest_path))};
  });
}

/** The Markdown file. A license text identical to one printed before is referred to, not repeated. */
export function render(crates, pkg = 'arqlet-wasm', target = 'wasm32-unknown-unknown') {
  const out = [
    '# Third-party notices',
    '',
    `The WebAssembly module in this package contains the Rust crates listed below, each under the license named, and their`,
    `copyright and license notices follow. Arqlet itself is licensed under either of the Apache License, Version 2.0`,
    `(LICENSE-APACHE) or the MIT license (LICENSE-MIT), at your option.`,
    '',
    `Generated by tools/third-party-notices.mjs from the crates \`cargo tree -p ${pkg} --target ${target}\` links. Do not edit by hand.`,
    '',
  ];
  const printed = new Map();
  for (const c of crates) {
    out.push(`## ${c.name} ${c.version}`, '', `License: ${c.license}`);
    if (c.repository) out.push(`Source: ${c.repository}`);
    out.push('');
    if (c.files.length === 0) out.push('NO LICENSE FILE IN THE CRATE: the license expression above is all that is known.', '');
    for (const f of c.files) {
      const hash = createHash('sha256').update(f.text).digest('hex');
      if (printed.has(hash)) {
        out.push(`### ${f.file}`, '', `Identical to ${printed.get(hash)}.`, '');
      } else {
        printed.set(hash, `${c.name} ${c.version}, ${f.file}`);
        out.push(`### ${f.file}`, '', '```text', f.text, '```', '');
      }
    }
  }
  return out.join('\n');
}

/** The notices of what `pkg` links for `target`, as one string. */
export function notices(pkg = 'arqlet-wasm', target = 'wasm32-unknown-unknown') {
  return render(collect(pkg, target), pkg, target);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const value = name => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
  const pkg = value('--package') ?? 'arqlet-wasm';
  const target = value('--target') ?? 'wasm32-unknown-unknown';
  const crates = collect(pkg, target);
  if (args.includes('--check')) {
    const missing = crates.filter(c => c.files.length === 0).map(c => `${c.name} ${c.version}`);
    if (missing.length) { console.error(`No license file in: ${missing.join(', ')}`); process.exit(1); }
  } else {
    process.stdout.write(render(crates, pkg, target) + '\n');
  }
}
